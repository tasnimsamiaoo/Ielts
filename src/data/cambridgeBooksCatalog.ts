// LocalStorage key for user imported tests
const CUSTOM_TESTS_STORAGE_KEY = 'ielts_imported_custom_tests';

/**
 * Get all user imported custom tests from browser localStorage
 */
export function getStoredCustomTests(): FullMockExamDataset[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(CUSTOM_TESTS_STORAGE_KEY);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch {
    return [];
  }
}

/**
 * Save a newly imported custom test to browser localStorage
 */
export function saveCustomTest(test: FullMockExamDataset): void {
  if (typeof window === 'undefined') return;
  try {
    const current = getStoredCustomTests();
    const updated = [test, ...current.filter((t) => t.examId !== test.examId)];
    localStorage.setItem(CUSTOM_TESTS_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Failed to save custom test to localStorage:', err);
  }
}

/**
 * Remove an imported test from localStorage
 */
export function deleteCustomTest(testId: string): void {
  if (typeof window === 'undefined') return;
  try {
    const current = getStoredCustomTests();
    const updated = current.filter((t) => t.examId !== testId);
    localStorage.setItem(CUSTOM_TESTS_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Failed to delete custom test:', err);
  }
}

